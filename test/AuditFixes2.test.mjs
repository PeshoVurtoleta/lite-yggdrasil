// test/AuditFixes2.test.mjs -- UNIT AF2 rows: AF2-1 bytecode budget, AF2-2 invalid-cursor NaN, AF2-3 readCounters
// NaN length, AF2-4 COUNTERS descriptor (ruling R-A5). Written FROM THE SPEC, not from engine output.
// Row kinds: FAIL-ON-OLD (red on the before build), PIN (passes on both).
// YG_ENGINE=<abs path> overrides the engine under test (revert-check on .handoff/af2-before/Yggdrasil.js).
// ASCII only.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';

const ENGINE_PATH = process.env.YG_ENGINE
  ? path.resolve(process.env.YG_ENGINE)
  : path.resolve(new URL('../Yggdrasil.js', import.meta.url).pathname);
const ENGINE_URL = pathToFileURL(ENGINE_PATH).href;
const { SumSequence } = await import(ENGINE_URL);

// V8 --max-inlined-bytecode-size is 460: a function of 460 bytes or more is never inlined.
const LIMIT = 460;

const SCRIPT = `
import { SumSequence } from ${JSON.stringify(ENGINE_URL)};
const v = new SumSequence(64, { leafSize: 4, dims: 2 });
for (let i = 0; i < 20; i++) v.insertAt(i, i + 1, 1, 2);
for (let k = 0; k < 50; k++) { v.getMeasure(3, 0); v.entityAt(3); v.indexAtSum(0, 5); v.sumBefore(0, 5); }
`;

function bytecodeLengths(name) {
  const r = spawnSync(process.execPath,
    ['--print-bytecode', '--print-bytecode-filter=' + name, '--input-type=module', '-e', SCRIPT],
    { encoding: 'utf8', timeout: 60000, maxBuffer: 64 * 1024 * 1024 });
  assert.ok(!r.error, name + ': child error ' + (r.error && r.error.message));
  assert.equal(r.status, 0, name + ': child exit ' + r.status + ' ' + r.stderr);
  const lines = r.stdout.split('\n');
  const out = [];
  let cur = null;
  for (const ln of lines) {
    const h = /^\[generated bytecode for function: (\S+) /.exec(ln);
    if (h) { cur = h[1]; continue; }
    const b = /^Bytecode length: (\d+)/.exec(ln);
    if (b && cur === name) { out.push(Number(b[1])); cur = null; }
  }
  return out;
}

function budgetRow(name, kind) {
  test('AF2-1 [' + kind + ']: SumSequence.prototype.' + name + ' bytecode < ' + LIMIT, () => {
    const ls = bytecodeLengths(name);
    assert.ok(ls.length >= 1, name + ': no Bytecode length line found (fail closed)');
    for (const n of ls) assert.ok(n < LIMIT, name + ': bytecode length ' + n + ' >= ' + LIMIT);
  });
}
budgetRow('getMeasure', 'FAIL-ON-OLD'); // 464 on the before build
budgetRow('entityAt', 'PIN');
budgetRow('indexAtSum', 'PIN');
budgetRow('sumBefore', 'PIN');

// FAIL-ON-OLD: R-A5, the writable static was reassignable.
test('AF2-4 [FAIL-ON-OLD]: SumSequence.COUNTERS is non-writable, non-configurable, frozen, stable', () => {
  const d = Object.getOwnPropertyDescriptor(SumSequence, 'COUNTERS');
  assert.ok(d, 'descriptor present');
  assert.equal(d.writable, false);
  assert.equal(d.configurable, false);
  assert.ok(Object.isFrozen(d.value), 'value frozen');
  assert.equal(SumSequence.COUNTERS, d.value);
  assert.equal(SumSequence.COUNTERS, SumSequence.COUNTERS);
  assert.throws(() => { 'use strict'; SumSequence.COUNTERS = {}; }, TypeError);
  assert.equal(SumSequence.COUNTERS, d.value, 'unchanged after the failed assignment');
});

// FAIL-ON-OLD: `out.length < 12` is false for NaN, so the old build fell through to out.set (generic TypeError).
// ygFail(token, detail) throws RangeError(token + ' ' + detail) (Yggdrasil.js:82-84). Since R-A8 (0.1.1) the cached
// %TypedArray%.prototype toStringTag brand runs first, so this forged object gets the brand text; a genuine short
// Int32Array with an own NaN `length` reaches the true-length check.
test('AF2-3 [FAIL-ON-OLD]: readCounters(forged NaN length) throws the engine counters error', () => {
  const v = new SumSequence(16, { leafSize: 4, dims: 1 });
  const forged = Object.create(Int32Array.prototype, { length: { value: NaN } });
  assert.throws(() => v.readCounters(forged), (e) => {
    assert.ok(e instanceof RangeError, 'RangeError, got ' + e);
    assert.equal(e.message, 'counters out must be an Int32Array');
    return true;
  });
  const short = new Int32Array(4);
  Object.defineProperty(short, 'length', { value: NaN });
  assert.throws(() => v.readCounters(short), (e) => {
    assert.ok(e instanceof RangeError, 'RangeError, got ' + e);
    assert.equal(e.message, 'counters out.length must be >= 12');
    return true;
  });
  // control: real arrays
  v.readCounters(new Int32Array(12));
  assert.throws(() => v.readCounters(new Int32Array(11)), (e) => {
    assert.ok(e instanceof RangeError);
    assert.equal(e.message, 'counters out.length must be >= 12');
    return true;
  });
});

// PIN: an invalid cursor answers NaN for offset(d) / measure(d), every d.
test('AF2-2 [PIN]: invalid cursor offset(d) / measure(d) are NaN for every d < dims (dims 1 and 4)', () => {
  for (const dims of [1, 4]) {
    const v = new SumSequence(16, { leafSize: 4, dims });
    const c = v.cursor();
    assert.equal(c.valid, false, 'fresh cursor is invalid (dims ' + dims + ')');
    for (let d = 0; d < dims; d++) {
      assert.ok(Number.isNaN(c.offset(d)), 'offset ' + d + ' dims ' + dims);
      assert.ok(Number.isNaN(c.measure(d)), 'measure ' + d + ' dims ' + dims);
    }
  }
});
